//! `Probe<B>` is `B` with counters and faults, not a different backend: a
//! trainer test that wraps `CpuBackend` in it must run the CPU's overrides,
//! not the trait defaults.

mod common;

use std::sync::atomic::{AtomicUsize, Ordering};

use common::Probe;
use ojas_core::{forward_backend_methods, Backend, BackendId, Budget, OjasError, Tensor};
use ojas_cpu::CpuBackend;

/// Forwards every method to `inner` except
/// `causal_sdpa_backward_recompute`, which `Spy` overrides.
macro_rules! all_but_recompute {
    (causal_sdpa_backward_recompute, { $($item:tt)* }) => {};
    ($name:ident, { $($item:tt)* }) => {
        $($item)*
    };
}

/// A backend whose `causal_sdpa_backward_recompute` is an override: it
/// counts the call and answers with its own marker error.
struct Spy {
    inner: CpuBackend,
    recomputes: AtomicUsize,
}

impl Backend for Spy {
    ojas_core::with_backend_methods!(
        forward_backend_methods,
        { self, self.inner, none, all_but_recompute }
    );
    fn causal_sdpa_backward_recompute(
        &self,
        _: &Tensor,
        _: &Tensor,
        _: &Tensor,
        _: &Tensor,
        _: Option<usize>,
    ) -> Result<(Tensor, Tensor, Tensor), OjasError> {
        self.recomputes.fetch_add(1, Ordering::SeqCst);
        Err(OjasError::Backend {
            id: BackendId::Cpu,
            detail: "spy:recompute".into(),
        })
    }
}

#[test]
fn the_probe_reaches_the_inner_recompute_override() {
    let spy = Spy {
        inner: CpuBackend::new(Budget::new(1 << 20)),
        recomputes: AtomicUsize::new(0),
    };
    let probe = Probe::new(&spy);
    let t = Tensor::from_f32(&[1.0], &[1], &Budget::new(1 << 10)).unwrap();
    let err = probe
        .causal_sdpa_backward_recompute(&t, &t, &t, &t, None)
        .unwrap_err();
    assert!(err.to_string().contains("spy:recompute"), "{err}");
    assert_eq!(spy.recomputes.load(Ordering::SeqCst), 1);
    assert_eq!(probe.count("causal_sdpa_backward_recompute"), 1);
}

/// The CPU scales a uniquely owned gradient in place with no charge; the
/// trait default builds and charges a broadcast operand and a new product.
#[test]
fn the_probe_runs_the_cpu_scale_grad_in_place() {
    let probe = Probe::new(CpuBackend::new(Budget::new(1 << 20)));
    let mut grad = Tensor::from_f32(&[1.0, -2.0, 4.0, 0.5], &[2, 2], probe.budget()).unwrap();
    let live = probe.budget().live_bytes().unwrap();
    probe.budget().reset_peak();
    probe.scale_grad(&mut grad, 0.25).unwrap();
    assert_eq!(grad.to_f32_vec().unwrap(), vec![0.25, -0.5, 1.0, 0.125]);
    assert_eq!(
        probe.budget().peak_bytes(),
        live,
        "scaled in place, no charge"
    );
    assert_eq!(probe.count("scale_grad"), 1);
}

/// `bf16_operands` is the backend's, not the trait default's `false`.
#[test]
fn the_probe_reports_the_inner_bf16_operands() {
    let probe = Probe::new(CpuBackend::new(Budget::new(1 << 20)));
    assert!(probe.inner().bf16_operands());
    assert!(probe.bf16_operands());
}

/// Adversarial: every method `Probe` leaves to the trait default is a way a
/// probe-based test silently exercises something other than the backend.
/// `CpuBackend` implements the hybrid sigmoid; the probe must give what the
/// CPU gives, not the trait's Unsupported default.
#[test]
fn the_probe_runs_the_cpu_sigmoid_forward() {
    let probe = Probe::new(CpuBackend::new(Budget::new(1 << 20)));
    let x = Tensor::from_f32(&[0.0, 1.0, -2.0], &[3], probe.budget()).unwrap();
    let want = probe
        .inner()
        .sigmoid_forward(&x)
        .unwrap()
        .to_f32_vec()
        .unwrap();
    let got = probe
        .sigmoid_forward(&x)
        .expect("Probe<Cpu>::sigmoid_forward fell to the Unsupported trait default")
        .to_f32_vec()
        .unwrap();
    assert_eq!(got, want);
}

/// Card ft-fe7dcee6 criterion 4, enforced mechanically: every method in
/// `ojas_core::BACKEND_METHODS` is either generated by the forwarding macro
/// (absent from `Probe`'s impl) or written by `Probe` with a body that calls
/// `self.inner.<name>(`. A written method that answered itself would run a
/// trait default instead of the wrapped backend's override.
#[test]
fn every_written_probe_method_calls_the_inner_method() {
    let src = include_str!("common/mod.rs");
    let start = src
        .find("impl<B: Backend> Backend for Probe<B> {")
        .expect("the Probe impl");
    let body = &src[start..];
    let body = &body[..body.find("\n}\n").expect("end of the Probe impl")];
    let mut written = 0;
    for name in ojas_core::BACKEND_METHODS {
        let Some(at) = body.find(&format!("\n    fn {name}(")) else {
            continue;
        };
        written += 1;
        let rest = &body[at + 1..];
        let end = rest[1..].find("\n    fn ").map_or(rest.len(), |n| n + 1);
        // rustfmt may break `self.inner` and `.name(` across lines.
        let compact: String = rest[..end].split_whitespace().collect();
        assert!(
            compact.contains(&format!("self.inner.{name}(")),
            "Probe::{name} does not call the inner backend's {name}"
        );
    }
    assert!(
        written > 20,
        "the scan found only {written} written methods"
    );
}

/// Card ft-fe7dcee6 criterion 4: every name `forward_unwritten!` excludes
/// from generation must be written by `Probe`. An excluded name `Probe` does
/// not write still compiles (the trait supplies a default) and would run
/// that default instead of the wrapped backend's method.
#[test]
fn every_name_excluded_from_generation_is_written_by_probe() {
    let src = include_str!("common/mod.rs");
    let macro_start = src
        .find("macro_rules! forward_unwritten {")
        .expect("the forward_unwritten macro");
    let macro_body = &src[macro_start..];
    let macro_body = &macro_body[..macro_body.find("\n}\n").expect("end of the macro")];
    let impl_start = src
        .find("impl<B: Backend> Backend for Probe<B> {")
        .expect("the Probe impl");
    let impl_body = &src[impl_start..];
    let impl_body = &impl_body[..impl_body.find("\n}\n").expect("end of the Probe impl")];
    let excluded: Vec<&str> = macro_body
        .lines()
        .filter_map(|line| {
            let rest = line.trim_start().strip_prefix('(')?;
            let name = &rest[..rest.find(',')?];
            (name != "$name:ident").then_some(name)
        })
        .collect();
    assert!(
        excluded.len() > 30,
        "the scan found only {} excluded names",
        excluded.len()
    );
    for name in &excluded {
        assert!(
            ojas_core::BACKEND_METHODS.contains(name),
            "{name} is excluded but is not a Backend method"
        );
        assert!(
            impl_body.contains(&format!("\n    fn {name}(")),
            "{name} is excluded from generation but Probe does not write it"
        );
    }
}
