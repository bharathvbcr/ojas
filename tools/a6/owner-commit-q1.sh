TRAILER="Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"

commit() { # commit <worktree> <expected branch> <subject> <body>
  local wt="$R/$1" want=$2 subject=$3 body=$4
  local br; br=$(git -C "$wt" rev-parse --abbrev-ref HEAD)
  [ "$br" = "$want" ] || { echo "REFUSED $1: on $br, expected $want"; exit 1; }
  git -C "$wt" add -A
  if git -C "$wt" diff --cached --quiet; then echo "nothing to commit in $1"; return; fi
  echo "--- $1 ($br):"; git -C "$wt" diff --cached --stat | tail -40
  git -C "$wt" commit -q -m "$subject" -m "$body" -m "$TRAILER"
  git -C "$wt" log --oneline -1
}

