#!/bin/bash
# ojas-a6: commit the nine lanes on their own branches, verify them all, and merge them into LOCAL main
# only if every step is green. Nothing is pushed. Run by the owner:
#   ! bash backups/a6-tools/owner-merge.sh
# Stops at the first red step, at a merge conflict, or if a lane's files overlap main's dirty files
# (a peer has .gitignore and bench/* uncommitted in main; those are never staged or committed here).
set -eu
R=/Users/bharath/Code/research
M="$R/ojas"
T="$M/backups/a6-tools"
TRAILER="Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"

commit() { # commit <worktree> <branch> <subject> <body>
  local wt="$R/$1"
  [ "$(git -C "$wt" rev-parse --abbrev-ref HEAD)" = "$2" ] || { echo "REFUSED $1: not on $2"; exit 1; }
  git -C "$wt" add -A
  if git -C "$wt" diff --cached --quiet; then echo "nothing to commit in $1"; return; fi
  git -C "$wt" commit -q -m "$3" -m "$4" -m "$TRAILER"; git -C "$wt" log --oneline -1
}

# 1. Commit every lane first (idempotent: "nothing to commit" when already done).
bash "$T/owner-commit-q1.sh"
commit ojas-a6-docsync gp/a6-docsync \
  "docs: ojas-qwen35 README and dtype-policy match the committed 2B Tape, bf16 and LoRA rows" \
  "ft-531216ed criterion 4 and ft-3cc9ed3f criterion 8 (Fable: both close on docs). The README's 'not measured' list is replaced by the measured Tape rows (2026-10-11-bf16-frozen-base, 2026-10-15-qwen35-2b-tape-gate, 2026-10-17-lora-step), and the provider 2B save/load row is marked retired (Fable 2026-10-15). dtype-policy states that Metal widens each Bf16 matmul operand into a charged f32 copy per call (backend.rs:364-369) with no bf16 GEMM, and that the LoRA rows have no widening column."
commit ojas-a6-stepcost gp/a6-stepcost \
  "ojas-metal: scan a frozen weight once (freeze_checked) and refuse writes to it; bench arms for the LoRA step A/B" \
  "ft-2bbced18 criterion 2. MetalBackend::freeze_checked scans a frozen weight's window once and marks it by buffer id. linear, linear_bwd, linear_bwd_input, embed and linear_ce then skip their per-call finite scan on it, and scale, kv_write, accumulate, adamw and muon refuse it. A faulting scan clears the mark at the next sync, and free() drops it. Opt-in and Metal-only; the generic hook belongs to the phase-B StepProvider (ft-b5e64557; ft-fe7dcee6). Criterion 3 was already met on main (tape.rs:978, :1200). New gpu_memory_rows arms tape-lora-checked and tape-lora-fulldw (it refuses unless every base linear gets a gradient), plus QWEN35_MEM_PHASES, for criteria 1 and 4. Adversarial pass: 3 defects fixed."
commit ojas-a6-preflight gp/a6-preflight \
  "ojas-model: memory pre-flight for the LoRA step, calibrated from the committed rows, plus a budgeted dry run" \
  "ft-b5e64557 criterion 10. Calibration fits peak(T) = c0 + c1*T per snapshot from bench/results/2026-10-17-lora-step/rows.jsonl. plan() rounds to the run's buckets and refuses with PreflightRefusal { tokens, bucket, estimated, cap, live } (no rows means refuse, never pass; extrapolation is flagged). dry_run() runs the step once at the widest bucket under a child Budget and maps CapacityExceeded to the same refusal. Wiring before step 0 is phase A's StepProvider."
commit ojas-a6-adamw100 gp/a6-adamw100 \
  "ojas-model: AdamW matches torch.optim.AdamW over 100 steps on CPU and Metal" \
  "ft-b5e64557 criterion 7. adamw_oracle.py: torch fp32 and fp64 runs of the LoRA recipe (betas 0.9/0.999, eps 1e-8, wd 0.01; lr 2e-4 and 1e-4), with closed-form gradients reproduced bit for bit in Rust and zero-gradient steps. The bound is 4x the measured fp32-vs-fp64 gap. adamw_torch_100.rs runs CPU Exact, CPU Fast and Metal at steps 1/10/50/100, with a sensitivity test showing a wrong decay or step count misses the bound. The fixture is generated by the verification batch and committed after it."
commit ojas-a6-merge gp/a6-merge \
  "ojas-model: merged bf16 LoRA weights for export (one rounding), by HF name" \
  "ft-58e316a9, ojas side. merged_weight_bf16 computes W + (alpha/r)*B*A in f32 and rounds once (f32_to_bf16, RNE), without mutating the LoraLinear. Qwen35Lora::merge_bf16 yields (HF name, bf16 tensor) through LoraTarget::fuse_b to a sink, one weight at a time. merge's shape checks and product are now shared helpers, with behaviour unchanged. Over a fake-quant base the target is the file's own dequant(Q(W)), so both arms export the same way."
commit ojas-a6-runbook gp/a6-runbook \
  "docs: the Lappi LoRA training runbook for the Mac (bf16 and fake-quant q8 arms)" \
  "The ordered path from today to the reduced quantised 2B run (Fable's 2026-10-17 order): prerequisites, owners, commands that exist today, gates, memory and wall-time notes, and the steps still BLOCKED (phase A; Lappi's torch driver, converter and gate tool; Lappi amendment 3's v6 shard rebuild)."

# 2. Verify every lane.
bash "$T/owner-batch.sh"
S="$T/logs/SUMMARY.txt"
if grep -E 'exit=[1-9]|failed=[1-9]' "$S"; then echo "RED: not merging. See $S"; exit 1; fi
if grep -E 'differ|EOF|No such file' "$T/logs/fq8-default-cmp.log"; then
  echo "RED: the default fixture no longer regenerates byte for byte; not merging"; exit 1
fi

# 3. The batch rustfmt'ed every lane and generated two fixtures: commit those on each lane's branch.
commit ojas-a6-fq8 gp/a6-fq8 "ojas-model: generated qwen35_tiny_fq8 base and qwen35_tiny_lora_fq8 references" \
  "Generated by ojas-oracle/python/qwen35_fakequant_base.py (mlx 0.31.2) and qwen35_lora_fixture.py --base (torch 2.13); manifest.json records the call and sha256 of every file. Also rustfmt from the verification batch."
commit ojas-a6-adamw100 gp/a6-adamw100 "ojas-model: generated adamw_100 torch fixture" \
  "Generated by ojas-oracle/python/adamw_oracle.py (torch 2.13); manifest.json records the versions, args and sha256. Also rustfmt from the verification batch."
for pair in ojas-a6-train:gp/a6-train ojas-a6-valuece:gp/a6-valuece ojas-a6-adapters:gp/a6-adapters \
            ojas-a6-stepcost:gp/a6-stepcost ojas-a6-preflight:gp/a6-preflight ojas-a6-merge:gp/a6-merge; do
  commit "${pair%%:*}" "${pair#*:}" "rustfmt from the a6 verification batch" "Formatting only; no logic change."
done

# 4. Merge into local main, one lane at a time; never over main's dirty files.
[ "$(git -C "$M" rev-parse --abbrev-ref HEAD)" = main ] || { echo "REFUSED: main checkout is not on main"; exit 1; }
DIRTY=$( { git -C "$M" diff --name-only; git -C "$M" diff --cached --name-only; } | sort -u)
for b in gp/a6-train gp/a6-valuece gp/a6-adapters gp/a6-fq8 gp/a6-docsync gp/a6-stepcost gp/a6-preflight gp/a6-adamw100 gp/a6-merge gp/a6-runbook; do
  CHANGED=$(git -C "$M" diff --name-only main..."$b" | sort -u)
  OVER=$(comm -12 <(printf '%s\n' "$DIRTY") <(printf '%s\n' "$CHANGED") | sed '/^$/d')
  [ -z "$OVER" ] || { echo "REFUSED $b: it changes files dirty in main: $OVER"; exit 1; }
  git -C "$M" merge --no-ff -q -m "Merge branch '$b'" -m "$TRAILER" "$b" || { echo "CONFLICT merging $b; resolve, or abort with: git -C $M merge --abort"; exit 1; }
  git -C "$M" log --oneline -1
done

# 5. Regenerate the site for the changed docs, and check it.
( cd "$M" && go run scripts/sitegen/main.go && go run scripts/sitegen/main.go -check )
if ! git -C "$M" diff --quiet -- site; then
  git -C "$M" add site
  git -C "$M" commit -q -m "site: regenerate the reference pages after the a6 merges" -m "$TRAILER"
  git -C "$M" log --oneline -1
fi

# 6. The merged main builds and the touched suites pass (own target dir; no peer shares it).
step_main() { # step_main <label> <cargo subcommand> <args...>
  local label=$1 sub=$2; shift 2
  set +e
  env CARGO_TARGET_DIR="$M/target-a6-main" perl -e 'alarm shift; exec @ARGV or die' 3600 \
    bash "$R/Lappi-decision/tools/mac_heavy.sh" "a6-main-$label" \
    cargo "$sub" --manifest-path "$M/Cargo.toml" "$@" > "$T/logs/main-$label.log" 2>&1
  local rc=$?
  set -e
  echo "main-$label exit=$rc $(grep -E '^test result:' "$T/logs/main-$label.log" | awk '{p+=$4; f+=$6} END {printf "passed=%d failed=%d", p, f}')"
}
step_main test test -p ojas-train -p ojas-autograd -p ojas-model -p ojas-metal -p ojas-qwen35 --no-fail-fast
step_main clippy clippy -p ojas-train -p ojas-autograd -p ojas-model -p ojas-metal -p ojas-qwen35 --all-targets -- -D warnings
echo "Done. Local main is ahead of origin; nothing was pushed."
